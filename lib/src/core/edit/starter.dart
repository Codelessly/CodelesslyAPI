/// The base: [baseSegments] assembled for [form], with the node types and
/// actions of [catalog] restricted by [profile] (the file form: every type;
/// the runtime form: [TrustProfile.agent] unless given). [kind] (runtime) is
/// `card`, `page` or `app`. [docsTool]: `ui_docs` is offered (runtime).
/// [segments] and [pages] default to the generated ones; the generator
/// passes the ones it just made.
String baseDocument({
  BaseForm form = BaseForm.runtime,
  Catalog catalog = Catalog.core,
  TrustProfile? profile,
  String kind = 'card',
  bool docsTool = true,
  DesignSystem? designSystem,
  List<BaseSegment>? segments,
  List<DocPage>? pages,
  List<DocTask>? tasks,
}) {
  final runtime = form == BaseForm.runtime;
  final p = profile ?? (runtime ? TrustProfile.agent : TrustProfile.none);
  final ds = designSystem;
  // A design system's components are node types like any other.
  final slice = p.restrict(ds == null ? catalog : ds.catalogOver(catalog));
  final has = slice.widget;
  final conditions = {
    form.name,
    if (runtime) kind,
    p.scripts ? 'scripts' : 'noScripts',
    if (runtime) docsTool ? 'docsTool' : 'noDocsTool',
    if (!runtime || docsTool) 'index',
    ds == null ? 'noDesignSystem' : 'designSystem',
  };
  final b = StringBuffer();
  for (final s in segments ?? baseSegments) {
    if (s.when.every(conditions.contains)) b.write(s.text);
  }
  final fills = <String, String Function()>{
    'baseTypes': () => _baseTypes(slice, without: {...?ds?.manifest.replaces}),
    'designSystem': () => ds == null ? '' : designSystemSection(ds, docsTool: runtime && docsTool),
    'replaced': () => ds == null || ds.manifest.replaces.isEmpty
        ? ''
        : '${ds.name}\'s components stand in for ${[for (final t in ds.manifest.replaces) '`$t`'].join(', ')}: use them.',
    'childrenTable': () => _childrenTable(slice),
    'ops': () => [
      for (final s in EditOp.specs)
        if (s.op != ScriptsOp.opName || p.scripts)
          '- `${s.op}` (${[for (final f in s.fields)
            if (f.key != 'op') '${f.key}${f.required ? '' : '?'}'].join(', ')}): ${firstSentences(s.doc, 2, max: 300)}',
    ].join('\n'),
    'actionTypes': () => [for (final a in slice.actions) '`${a.type}`'].join(', '),
    'variableTypes': () => [for (final t in VariableType.values) '`${t.name}`'].join(', '),
    'scriptCapabilities': () => (p.scriptCapabilities ?? ScriptCapability.values.toSet()).map((c) => c.id).join(', '),
    'buildExample': () => '```json\n${jsonEncode(starterBuildExample)}\n```',
    'editExample': () => '```json\n${jsonEncode(starterEditExample)}\n```',
    'index': () => docsIndex(catalog: catalog, profile: p, form: form, pages: pages, tasks: tasks),
    'button': () => ds != null && ds.manifest.replaces.contains('filledButton')
        ? 'one of the design system\'s button components, with its label'
        : has('filledButton') != null
        ? 'a `filledButton` with "label" and "style"'
        : 'a row with a fill and padding whose child is a text',
  };
  var text = b.toString().replaceAllMapped(RegExp(r'\{\{(\w+)\}\}'), (m) {
    final f = fills[m[1]];
    if (f == null) throw StateError('base: no fill for {{${m[1]}}}');
    return f();
  });
  text = text.replaceAll(RegExp(r'\n{3,}'), '\n\n');
  return runtime ? toRuntimeLinks(text) : text;
}

/// The runtime form of the base: the system prompt of a model that streams
/// `ui_apply` ops ([baseDocument] with [BaseForm.runtime]).
String runtimeStarter({
  Catalog catalog = Catalog.core,
  TrustProfile? profile,
  String kind = 'card',
  bool docsTool = true,
  DesignSystem? designSystem,
}) => baseDocument(catalog: catalog, profile: profile, kind: kind, docsTool: docsTool, designSystem: designSystem);

/// [text]'s links as `ui_docs` lookups: `[x](forms.md#forms-validation)` is
/// `x (ui_docs "forms-validation")`, `[x](forms.md)` is `x (ui_docs
/// "forms")`; a link within the base keeps its text only.
String toRuntimeLinks(String text) => text
    .replaceAll(RegExp(r'^<a id="[^"]+"></a>\n', multiLine: true), '')
    .replaceAllMapped(RegExp(r'\[([^\]]+)\]\((?:STARTER\.md)?#base-[\w-]+\)'), (m) => m[1]!)
    .replaceAllMapped(RegExp(r'\[([^\]]+)\]\((?:STARTER|RUNTIME_STARTER|index|README)\.md[^)]*\)'), (m) => m[1]!)
    .replaceAllMapped(RegExp(r'\[([^\]]+)\]\(([\w-]+)\.md#(?:page-)?([\w-]+)\)'), (m) => '${m[1]} (ui_docs "${m[3]}")')
    .replaceAllMapped(RegExp(r'\[([^\]]+)\]\(([\w-]+)\.md\)'), (m) => '${m[1]} (ui_docs "${m[2]}")');

String _baseTypes(Catalog slice, {Set<String> without = const {}}) {
  final b = StringBuffer()
    ..writeln('| type | takes | props (the base ones; all of them on its page) |')
    ..writeln('|---|---|---|');
  for (final e in baseProps.entries) {
    if (without.contains(e.key)) continue;
    final w = slice.widget(e.key);
    if (w == null) continue;
    final props = [
      for (final k in e.value)
        if (w.prop(k) case final PropDef<Object?> d) '`$k` ${propTypeLabel(d.type)}',
    ];
    b.writeln(
      '| [`${w.type}`](${_pageOf(w.type)}.md#node-${w.type}) | ${_takes(w)}${w.decorated ? '' : '; no decoration'} | ${props.join(', ')} |',
    );
  }
  return b.toString().trimRight();
}

String _takes(WidgetSpec w) => switch (w.children) {
  ChildModel.list => w.slots.isEmpty ? 'children' : 'children; slots ${w.slots.join(', ')}',
  ChildModel.slots => 'slots ${w.slots.join(', ')}',
  ChildModel.none => 'none',
};

/// Every allowed type by what it takes: children, slots or nothing.
String _childrenTable(Catalog slice) {
  final list = [
    for (final w in slice.widgets)
      if (w.children == ChildModel.list) w,
  ];
  final slots = [
    for (final w in slice.widgets)
      if (w.children == ChildModel.slots) w,
  ];
  final none = [
    for (final w in slice.widgets)
      if (w.children == ChildModel.none) w,
  ];
  return [
    '| takes | types |',
    '|---|---|',
    '| `children` (a list of ids) | ${[for (final w in list) w.slots.isEmpty ? '`${w.type}`' : '`${w.type}` (and slots ${w.slots.join(', ')})'].join(', ')} |',
    '| `slots` (name → id) | ${[for (final w in slots) '`${w.type}` (${w.slots.join(', ')})'].join(', ')} |',
    '| nothing | ${[for (final w in none) '`${w.type}`'].join(', ')} |',
  ].join('\n');
}

/// The page that documents node type, action, behavior or trigger [name].
String _pageOf(String name, [List<DocPage>? pages]) {
  for (final p in pages ?? docPages) {
    if (p.items.contains(name)) return p.id;
  }
  return 'values';
}

/// The index the base ends with: the task table (need → section) and the
/// pages with what each documents. In the runtime form, every entry is a
/// `ui_docs` topic.
String docsIndex({
  Catalog catalog = Catalog.core,
  TrustProfile? profile,
  BaseForm form = BaseForm.runtime,
  List<DocPage>? pages,
  List<DocTask>? tasks,
}) {
  final ps = pages ?? docPages;
  final ts = tasks ?? docTasks;
  final runtime = form == BaseForm.runtime;
  String fileOf(String anchor) {
    for (final p in ps) {
      if (anchor == 'page-${p.id}' || p.sections.any((s) => s.id == anchor)) return p.file;
    }
    for (final p in ps) {
      if (p.items.any((i) => RegExp(r'^(node|action|behavior|trigger)-').hasMatch(anchor) && anchor.endsWith('-$i'))) {
        return p.file;
      }
    }
    for (final p in ps) {
      if (anchor.startsWith('${p.id}-')) return p.file;
    }
    return anchor.startsWith('base-') ? 'STARTER.md' : 'index.md';
  }

  final b = StringBuffer();
  b.writeln(
    runtime
        ? 'Look up anything below with ui_docs {"topic": "<topic>"}: a page, a section, or any node type, action, trigger or behavior by name.'
        : 'Every page is in this folder; `index.md` has the full task table and an A–Z of every name.',
  );
  b.writeln();
  b.writeln('| You need | ${runtime ? 'ui_docs topic' : 'Open'} |');
  b.writeln('|---|---|');
  for (final t in ts) {
    b.writeln(
      runtime ? '| ${t.need} | "${t.anchor}" |' : '| ${t.need} | [${t.anchor}](${fileOf(t.anchor)}#${t.anchor}) |',
    );
  }
  b.writeln();
  for (final p in ps) {
    final items = runtime
        ? [
            for (final i in p.items)
              if (_allowed(catalog, profile, i)) i,
          ]
        : p.items;
    b.writeln(
      '- ${runtime ? '"${p.id}"' : '[${p.file}](${p.file})'}: ${p.title}.'
      '${items.isEmpty ? '' : ' Documents ${items.join(', ')}.'}',
    );
  }
  return toRuntimeLinksIf(b.toString(), runtime);
}

String toRuntimeLinksIf(String s, bool runtime) => runtime ? toRuntimeLinks(s) : s;

bool _allowed(Catalog catalog, TrustProfile? profile, String item) {
  final slice = (profile ?? TrustProfile.agent).restrict(catalog);
  if (catalog.widget(item) != null) return slice.widget(item) != null;
  if (catalog.action(item) != null) return slice.action(item) != null;
  // A behavior or trigger; else a type of a feature library [catalog] lacks.
  return _behavior(item) != null || TriggerType.values.any((t) => t.name == item);
}

/// Every topic [docsTopic] answers.
List<String> docsTopicNames({Catalog catalog = Catalog.core, List<DocPage>? pages}) => [
  for (final p in pages ?? docPages) ...[p.id, for (final s in p.sections) s.id],
  ...docAliases.keys,
  'scripts',
  'triggers',
  for (final x in TriggerType.values) x.name,
  for (final w in catalog.widgets) w.type,
  for (final a in catalog.actions) a.type,
  for (final f in BehaviorFields.all) f.key,
];

/// One topic, sized for a tool result (a few hundred tokens): a page (its
/// "When to use", minimal example and pitfalls, and the list of its
/// sections), a section of a page by its anchor, or a node type, action
/// type, trigger or behavior by name (or by its anchor, `node-slider`). What
/// [profile] does not allow says so: it is documented, not available.
String docsTopic(String topic,
    {Catalog catalog = Catalog.core, TrustProfile? profile, List<DocPage>? pages, DesignSystem? designSystem}) {
  // The design system's own documents and components first.
  if (designSystem != null) {
    final own = designSystemTopic(designSystem, topic);
    if (own != null) return own;
  }
  final p = profile ?? TrustProfile.agent;
  final slice = p.restrict(catalog);
  final ps = pages ?? docPages;
  var t = topic.trim().replaceFirst(RegExp(r'^[\w-]+\.md#?'), '');
  if (t.startsWith('page-')) t = t.substring(5);
  t = docAliases[t] ?? t;
  for (final page in ps) {
    if (page.id == t) return _pageTopic(page);
    for (final s in page.sections) {
      if (s.id == t) return _sectionTopic(page, s);
    }
    if (t == '${page.id}-when-to-use' || t == '${page.id}-minimal-example' || t == '${page.id}-pitfalls') {
      return _pageTopic(page);
    }
  }
  t = t.replaceFirst(RegExp(r'^(node|action|behavior|trigger)-'), '');
  if (t == 'scripts') return _scriptsTopic(p);
  if (t == 'triggers' || TriggerType.values.any((x) => x.name == t)) return _triggersTopic(t, ps);
  final w = catalog.widget(t);
  if (w != null) {
    final b = StringBuffer('# `${w.type}`\n\n');
    if (slice.widget(t) == null) {
      b.writeln('Not available here: this app does not allow this node type. Use another.\n');
    }
    if (w.doc.isNotEmpty) b.writeln('${firstSentences(w.doc, 3, max: 400)}\n');
    b.writeln(
      '- Takes: ${switch (w.children) {
        ChildModel.list => 'children${w.slots.isEmpty ? '' : ' (and slots ${w.slots.join(', ')})'}',
        ChildModel.slots => 'slots ${w.slots.join(', ')} (no children list)',
        ChildModel.none => 'no children',
      }}. Decoration: ${w.decorated ? 'yes' : 'no (fills, strokes and radius are ignored)'}.',
    );
    if (w.events.isNotEmpty) {
      b.writeln('- Triggers it fires: ${[for (final e in w.events) e.key].join(', ')} (the value as \${result}).');
    }
    b.writeln();
    b.writeln('| prop | type | |');
    b.writeln('|---|---|---|');
    for (final f in w.props.take(40)) {
      b.writeln('| `${f.key}` | ${propTypeLabel(f.type)} | ${firstSentences(f.doc, 1, max: 140)} |');
    }
    if (w.props.length > 40) b.writeln('\n${w.props.length - 40} more props not listed.');
    b.writeln();
    b.writeln(
      'Minimal: ${jsonEncode({
        'type': w.type,
        'layout': {
          'width': {'fill': 358},
          'height': w.children == ChildModel.none ? 48 : {'hug': 120},
        },
        if (w.children == ChildModel.list) 'children': ['${w.type}Child'],
        if (w.slots.isNotEmpty && w.children == ChildModel.slots) 'slots': {w.slots.first: '${w.type}${_cap(w.slots.first)}'},
      })}',
    );
    b.writeln('\nPatterns and pitfalls: ui_docs "${_pageOf(w.type, ps)}".');
    return b.toString();
  }
  final a = catalog.action(t);
  if (a != null) {
    final b = StringBuffer('# action `${a.type}`\n\n');
    if (slice.action(t) == null) b.writeln('Not available here: this app does not allow this action type.\n');
    if (a.doc.isNotEmpty) b.writeln('${firstSentences(a.doc, 3, max: 400)}\n');
    b.writeln('| field | type | |');
    b.writeln('|---|---|---|');
    for (final f in a.fields) {
      b.writeln('| `${f.key}` | ${propTypeLabel(f.type)} | ${firstSentences(f.doc, 1, max: 140)} |');
    }
    b.writeln(
      '\nIn a reaction: "actions": [{"trigger": {"type": "click"}, "actions": [{"type": "${a.type}", ...}]}]. '
      'More: ui_docs "${_pageOf(a.type, ps)}".',
    );
    return b.toString();
  }
  if (_behavior(t) case final f?) {
    final b = StringBuffer('# behavior `${f.key}`\n\nA node key beside "layout" and "props".\n\n${_fieldLine(f)}\n');
    final item = f.type.item;
    final fields = f.type.kind == PropKind.object
        ? f.type.fields
        : (item != null && item.kind == PropKind.object ? item.fields : const []);
    if (fields.isNotEmpty) {
      b.writeln('\n| field | type | |\n|---|---|---|');
      for (final x in fields.take(30)) {
        b.writeln('| `${x.key}` | ${propTypeLabel(x.type)} | ${firstSentences(x.doc, 1, max: 140)} |');
      }
    }
    b.writeln('\nMore: ui_docs "${_pageOf(f.key, ps)}".');
    return b.toString();
  }
  for (final page in ps) {
    if (page.items.contains(t)) {
      return '# `$t`\n\nNot available here: `$t` belongs to a feature library this app does not include. '
          'It is documented on the ${page.title} page (ui_docs "${page.id}").\n';
    }
  }
  if (RegExp(r'^(type|enum)-(\w+)$').firstMatch(t) case final m?) {
    if (_findType(catalog, m[2]!) case final type?) return _typeTopic(type);
  }
  return 'No topic "$topic". Topics: the pages ${[for (final page in ps) '"${page.id}"'].join(', ')}; a section by its id; '
      'any node type, action, trigger or behavior by name.';
}

String _pageTopic(DocPage p) {
  final b = StringBuffer('# ${p.title}\n\n${toRuntimeLinks(p.when).trim()}\n\n');
  final example = toRuntimeLinks(p.example).trim();
  if (example.length <= 1800) {
    b.writeln('$example\n');
  } else {
    b.writeln('Minimal example: ui_docs "${p.id}-minimal-example" (${example.length} characters).\n');
  }
  b.writeln(_trim(toRuntimeLinks(p.pitfalls).trim(), 1400));
  b.writeln();
  if (p.sections.isNotEmpty) {
    b.writeln('Sections (ui_docs "<id>"): ${[for (final s in p.sections) '"${s.id}" (${s.title})'].join(', ')}.');
  }
  if (p.items.isNotEmpty) b.writeln('Documents (ui_docs "<name>"): ${p.items.join(', ')}.');
  return b.toString();
}

String _sectionTopic(DocPage p, DocSection s) =>
    '# ${s.title}\n\n${_trim(toRuntimeLinks(s.text).trim(), 3000)}\n\n(From ${p.file}; the page: ui_docs "${p.id}".)\n';

String _trim(String s, int max) {
  if (s.length <= max) return s;
  final cut = s.lastIndexOf('\n', max);
  final body = s.substring(0, cut < max ~/ 2 ? max : cut);
  // Close an open code fence.
  final open = '```'.allMatches(body).length.isOdd;
  return '$body${open ? '\n```' : ''}\n\n(Shortened.)';
}

PropType? _findType(Catalog catalog, String name) {
  final seen = <String>{};
  PropType? walk(PropType t) {
    if (t.name == name && (t.kind == PropKind.object || t.kind == PropKind.enumeration)) return t;
    if (t.kind == PropKind.object) {
      if (!seen.add(t.name)) return null;
      for (final f in t.fields) {
        if (walk(f.type) case final r?) return r;
      }
    }
    if (t.item case final i?) return walk(i);
    return null;
  }

  for (final defs in [
    for (final w in catalog.widgets) w.props,
    for (final a in catalog.actions) a.fields,
    BehaviorFields.all,
  ]) {
    for (final d in defs) {
      if (walk(d.type) case final r?) return r;
    }
  }
  return null;
}

String _typeTopic(PropType t) {
  if (t.kind == PropKind.enumeration) return '# ${t.name}\n\nOne of: ${t.values.map((v) => '"$v"').join(', ')}.\n';
  final b = StringBuffer('# ${t.name}\n\n| field | type | |\n|---|---|---|\n');
  for (final f in t.fields.take(40)) {
    b.writeln('| `${f.key}` | ${propTypeLabel(f.type)} | ${firstSentences(f.doc, 1, max: 140)} |');
  }
  return b.toString();
}

/// What [TriggerType]s put in `${result}`, where it is not just the value.
const Map<String, String> _triggerResults = {
  'click': r'${result.x}, ${result.y}: where it landed in the node.',
  'changed': r'${result}: the new value of the input.',
  'drag':
      r'${result.dx}, ${result.dy} (this move), ${result.x}, ${result.y}; dragEnd when let go (${result.vx}, ${result.vy}: velocity).',
  'timer': r'"intervalMs": 1000 (a number or a formula), "when": a formula that must hold; ${result.tick} counts.',
  'frame':
      r'every frame while "when" holds: ${result.dt} (ms since the last), ${result.elapsed}, ${result.frame}. For physics and game loops.',
  'valueChanged': r'"variable": the name; runs when it changes.',
  'keyDown': r'"key": "space" or "ctrl+z"; ${result.key}.',
  'swipeLeft': r'also swipeRight, swipeUp, swipeDown: a fling.',
};

String _triggersTopic(String t, List<DocPage> ps) {
  final b = StringBuffer('# triggers\n\n');
  b.writeln(
    'A reaction: {"trigger": {"type": "<trigger>", ...}, "actions": [...]} in a node\'s "actions". A screen trigger (load, '
    'timer, frame, keyDown, valueChanged...) goes on the canvas. Trigger fields: "type", "intervalMs", "when", "variable", '
    '"key", "holdMs", "debounceMs".\n',
  );
  if (_triggerResults[t] case final r?) b.writeln('`$t`: $r\n');
  if (t != 'triggers') b.writeln('`$t` is documented on ui_docs "${_pageOf(t, ps)}".\n');
  b.writeln('Types: ${[for (final x in TriggerType.values) x.name].join(', ')}.\n');
  for (final e in _triggerResults.entries) {
    if (e.key != t) b.writeln('- `${e.key}`: ${e.value}');
  }
  return b.toString();
}

String _scriptsTopic(TrustProfile p) {
  final caps = p.scriptCapabilities ?? ScriptCapability.values.toSet();
  return '''# scripts

${p.scripts ? '' : 'Not available here: this app does not allow scripts. Use formulas, variables and reactions.\n\n'}Sandboxed JavaScript the document keeps in its "scripts" list, written with the scripts op:
{"op": "scripts", "set": {"place": {"params": ["cell", "digit"], "source": "const b = vars.get('board'); b[cell] = digit; vars.set('board', b); return b;", "capabilities": ["variables.read", "variables.write"]}}}.

- What it returns at its top level is its result. Params are variables in its source.
- vars.get(name), vars.set(name, value) (with the capabilities variables.read / variables.write) read and set the
  document's variables; the UI updates through what binds to them. A script cannot draw or touch nodes.
- Capabilities allowed here: ${[for (final c in caps) '${c.id} (${c.label})'].join(', ')}.
- A reaction runs it: {"type": "runScript", "script": "place", "arguments": {"cell": "\${index}", "digit": "\${result}"}}.
- A formula calls it: "\${= script.isSolved(board)}" (keep those pure: no vars.set).
- Limits: ${ScriptDef.defaultTimeoutMs} ms of computing (timeoutMs up to ${ScriptDef.maxTimeoutMs}), ${ScriptDef.defaultMemoryLimitMb} MB; no network, files or timers.
- Names: JavaScript identifiers, not ${ScriptDef.reservedNames.join(', ')}.
''';
}

