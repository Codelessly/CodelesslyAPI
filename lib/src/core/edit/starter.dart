// The docs a model or an agent is given: ONE BASE, plus links to the rest.
//
// The base is one document in two forms: the file-authoring form
// (docs/reference/STARTER.md: an agent writing files and checking them with
// the render command) and the runtime form (docs/reference/RUNTIME_STARTER.md
// and the system prompt of a model that streams `ui_apply` ops). Both are
// [baseDocument] over the same generated segments ([baseSegments]); they
// differ only by the envelope blocks the base template marks for one form.
// Its prose is tool/reference/templates/base.md; its tables are generated
// here from the declarations, restricted to what the trust profile allows.
//
// The rest is the reference's pages (docs/reference/<page>.md). The same
// pages, cut into sections ([docPages], generated by
// tool/reference/generate.dart into guide_topics.g.dart), are what the
// `ui_docs` tool answers ([docsTopic]); the index the base ends with
// ([docsIndex]) lists them. A link `forms.md#forms-validation` in the files
// form is `ui_docs "forms-validation"` in the runtime form: the same map.
