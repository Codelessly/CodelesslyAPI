/// Which form of the base: for an agent writing files, or for a model
/// streaming ops at run time.
enum BaseForm { files, runtime }

/// A piece of the base template: [text], included when every condition in
/// [when] holds (`files`, `runtime`, `card`, `page`, `app`, `scripts`,
/// `noScripts`, `docsTool`, `noDocsTool`).
final class BaseSegment {
  const BaseSegment(this.when, this.text);
  final List<String> when;
  final String text;
}

/// One section of a reference page: its anchor [id], [title] and Markdown
/// [text] (links as in the page files).
final class DocSection {
  const DocSection(this.id, this.title, this.text);
  final String id;
  final String title;
  final String text;
}

/// One page of the reference, as `ui_docs` serves it.
final class DocPage {
  const DocPage({
    required this.id,
    required this.title,
    required this.summary,
    required this.when,
    required this.example,
    required this.pitfalls,
    this.sections = const [],
    this.items = const [],
    this.words = 0,
  });

  /// The page's file stem and topic name (`forms`: forms.md).
  final String id;
  final String title;

  /// The first sentence of [when].
  final String summary;

  /// The page's "When to use", "Minimal example" and "Pitfalls" sections.
  final String when, example, pitfalls;

  /// Its other sections, each retrievable by id: the patterns and the
  /// generated reference tables.
  final List<DocSection> sections;

  /// The node types, behaviors, triggers and actions it documents.
  final List<String> items;

  /// The page's size in words.
  final int words;

  String get file => '$id.md';
}

/// A need and the section that answers it (the index's task table).
typedef DocTask = ({String need, String anchor});

