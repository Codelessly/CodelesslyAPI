// The built-in dictionary (docs/design/23-base-and-dictionary.md section 5.2):
// the words the notation has as definitions written in its base words, not
// as Dart code. Each is a file of dictionary/ ([builtInWords]); this writes
// their texts into lib/src/core/notation/dictionary.g.dart, which the
// expander reads (an app and the web read no files).
//
//   dart run tool/dictionary/generate.dart [--check]
//
// Run from the package root of an LF copy. --check says whether the file is
// up to date and exits 1 when it is not (test/notation_dictionary_test.dart
// runs the same comparison).
import 'dart:io';

/// The words of dictionary/ that are built in: each closed exactly over every
/// use (docs/design/base-inventory/CLOSURE.md) and was moved out of the
/// expander's code with the proof of note 23 section 5.2. A word is added
/// here only when that is so.
const builtInWords = ['computed'];

/// The generated file, from the dictionary folder [dir].
String generatedDictionary({String dir = 'dictionary'}) {
  final b = StringBuffer()
    ..writeln('// Generated by tool/dictionary/generate.dart from dictionary/ (the words of builtInWords). Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// The built-in dictionary (docs/design/23 section 5.2): words the notation has as')
    ..writeln('/// definitions written in its base words, each file\'s text by its name.')
    ..writeln('const Map<String, String> notationDictionaryTexts = {');
  for (final w in [...builtInWords]..sort()) {
    final text = File('$dir/$w.txt').readAsStringSync().replaceAll('\r\n', '\n');
    b.writeln("  '$w.txt': ${_literal(text)},");
  }
  b.writeln('};');
  return b.toString();
}

String _literal(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";

const generatedPath = 'lib/src/core/notation/dictionary.g.dart';

void main(List<String> args) {
  final want = generatedDictionary();
  final file = File(generatedPath);
  if (args.contains('--check')) {
    final have = file.existsSync() ? file.readAsStringSync().replaceAll('\r\n', '\n') : '';
    if (have != want) {
      stderr.writeln('$generatedPath is out of date: run dart run tool/dictionary/generate.dart');
      exit(1);
    }
    stdout.writeln('$generatedPath is up to date.');
    return;
  }
  file.writeAsStringSync(want);
  stdout.writeln('Wrote $generatedPath (${builtInWords.length} words).');
}
