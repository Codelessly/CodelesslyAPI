/// The fills the base template leaves to `baseDocument` (they depend on the
/// trust profile).
const _libFills = {
  'baseTypes', 'childrenTable', 'ops', 'actionTypes', 'variableTypes', 'scriptCapabilities', 'buildExample', //
  'editExample', 'index', 'button',
};

/// The reference files, by path relative to the package root.
Map<String, String> buildReference(String root) {
  final catalog = Catalog(root);
  final Map<String, dynamic> json = catalog.json;
  final assignment = assign(json);
  final r = Renderer(json, root, assignment);

  // The pages, then the base and the index (which link into them).
  final pages = <String, String>{
    for (final p in featurePages) p.file: r.featurePage(p),
    '$valuesPage.md': r.valuesPageText(),
  };
  pages.forEach(r.collect);
  final baseText = Renderer.anchorHeadings(r.template('base.md', keep: _libFills), 'base', prefix: 'base');
  r.collect('STARTER.md', baseText);
  final indexSource = r.template('index.md', keep: {'az', 'pageTable', 'movedGuide'});
  final tasks = [
    for (final m in RegExp(r'^\| (.+?) \| @@([\w.-]+) \|$', multiLine: true).allMatches(indexSource)) (need: m[1]!, anchor: m[2]!),
  ];
  // Anchors the index itself defines, so its own links resolve.
  r.collect('index.md', Renderer.anchorHeadings(indexSource, 'index'));
  r.collect('index.md', [for (final k in movedGuideSections.keys) '<a id="$k"></a>'].join());
  final words = {for (final e in pages.entries) e.key: wordCount(e.value)};
  final unknown = [for (final t in tasks) if (r.anchors[t.anchor] == null) t.anchor];
  if (unknown.isNotEmpty) throw StateError('index.md: tasks link to unknown anchors: ${unknown.join(', ')}');
  var index = indexSource
      .replaceAllMapped(RegExp(r'@@([\w.-]+)'), (m) {
        final file = r.anchors[m[1]!];
        if (file == null) throw StateError('index.md: task links to unknown anchor ${m[1]}');
        return '[$file#${m[1]}]($file#${m[1]})';
      })
      .replaceAll('{{az}}', r.az())
      .replaceAll('{{pageTable}}', Renderer.table(['Page', 'What it covers', 'Words'], [
        ['[STARTER.md](STARTER.md)', 'The base (give it up front): the document, layout, decoration, text, the base node types, state, reactions, the rules.', '${wordCount(baseText)}'],
        for (final p in featurePages) ['[${p.file}](${p.file})', _summary(pages[p.file]!, p.id), '${words[p.file]}'],
        ['[values.md](values.md)', _summary(pages['values.md']!, 'values'), '${words['values.md']}'],
      ]))
      .replaceAll('{{movedGuide}}', Renderer.table(['Old link', 'Now'], [
        for (final e in movedGuideSections.entries) ['<a id="${e.key}"></a>`index.md#${e.key}`', '[${e.value}](${e.value})'],
      ]));
  index = '${r.generatedNote()}\n${Renderer.anchorHeadings(index, 'index')}\n';
  final resolved = {for (final e in pages.entries) e.key: r.resolve(e.value, e.key)};
  final base = r.resolve(baseText, 'STARTER.md');
  index = r.resolve(index, 'index.md');

  // The base's segments and the pages' sections, as the package serves them.
  final segments = baseSegmentsOf(base);
  final docPages = [
    for (final p in featurePages) docPageOf(resolved[p.file]!, p),
    docPageOf(resolved['values.md']!, const PageDef(valuesPage)),
  ];
  String starter(api.BaseForm form) => api.baseDocument(
        form: form,
        catalog: form == api.BaseForm.files ? api.standardCatalog : api.Catalog.core,
        segments: segments,
        pages: docPages,
        tasks: tasks,
      );
  final starterFiles = '${r.generatedNote()}\n${starter(api.BaseForm.files)}';
  final starterRuntime = '<!-- Generated by tool/reference/generate.dart (runtimeStarter(): the base, runtime form, '
      'TrustProfile.agent over Catalog.core). Do not edit. -->\n${starter(api.BaseForm.runtime)}';

  final stubs = {for (final e in stubPages.entries) e.key: _stub(r, e.key, e.value)};
  String joined(List<String> texts) => texts.map((t) => Renderer.singleFile(t).trimRight()).join('\n\n---\n\n');
  final apiReference = joined([
    starterFiles,
    index,
    for (final p in featurePages) resolved[p.file]!,
    resolved['values.md']!,
  ]);

  // catalog.json: each item with the page and anchor that documents it.
  for (final e in (json['nodeTypes'] as Map).entries) {
    (e.value as Map)['docs'] = '${assignment[ItemKind.node]![e.key]}.md#node-${e.key}';
  }
  for (final e in (json['actions']['types'] as Map).entries) {
    (e.value as Map)['docs'] = '${assignment[ItemKind.action]![e.key]}.md#action-${e.key}';
  }
  for (final f in (json['behaviors']['fields'] as List).cast<Map>()) {
    f['docs'] = '${assignment[ItemKind.behavior]![f['key']]}.md#behavior-${f['key']}';
  }
  for (final t in (json['triggers']['types'] as List).cast<Map>()) {
    t['docs'] = '${assignment[ItemKind.trigger]![t['type']]}.md#trigger-${t['type']}';
  }

  final out = <String, String>{
    for (final e in resolved.entries) 'docs/reference/${e.key}': e.value,
    'docs/reference/index.md': index,
    'docs/reference/STARTER.md': starterFiles,
    'docs/reference/RUNTIME_STARTER.md': starterRuntime,
    for (final e in stubs.entries) 'docs/reference/${e.key}': e.value,
    'docs/reference/API_REFERENCE.md': '$apiReference\n',
    'docs/reference/catalog.json': '${const JsonEncoder.withIndent('  ').convert(json)}\n',
    'docs/reference/document.schema.json': '${const JsonEncoder.withIndent('  ').convert(SchemaBuilder().build())}\n',
    'docs/reference/_missing_docs.md': _missing(catalog),
    // The two tools a model is given, for the agent profile over the core.
    'docs/reference/ui_tools.json':
        '${const JsonEncoder.withIndent('  ').convert(api.uiTools(api.TrustProfile.agent.restrict(api.Catalog.core)))}\n',
    // The compact tools the runtime base goes with.
    'docs/reference/ui_tools.compact.json':
        '${const JsonEncoder.withIndent('  ').convert(api.uiTools(api.TrustProfile.agent.restrict(api.Catalog.core), compact: true))}\n',
    'lib/src/core/edit/guide_topics.g.dart': docsSource(segments, docPages, tasks),
  };
  out['docs/reference/index.json'] = '${const JsonEncoder.withIndent('  ').convert(_indexJson(r, docPages, tasks, out))}\n';
  out['docs/reference/README.md'] = '${r.generatedNote()}\n${r.template('README.md', fills: {
        'fileTable': () => Renderer.table(['File', 'What it is', 'Words', '≈ tokens'], [
              for (final f in _readmeFiles.entries)
                [
                  '[${f.key}](${f.key})',
                  f.value,
                  '${wordCount(out['docs/reference/${f.key}'] ?? '')}',
                  '${((out['docs/reference/${f.key}'] ?? '').length / 4).round()}',
                ],
            ]),
      })}\n';
  return out;
}

