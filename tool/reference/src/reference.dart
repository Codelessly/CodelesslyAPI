/// Words in [text] (whitespace-separated).
int wordCount(String text) => RegExp(r'\S+').allMatches(text).length;

String _summary(String page, String id) {
  final m = RegExp('<a id="$id-when-to-use"></a>\\n## [^\\n]*\\n+([^\\n]+(?:\\n[^\\n#<]+)*)').firstMatch(page);
  if (m == null) throw StateError('$id: no "When to use" section');
  final para = m[1]!.replaceAll('\n', ' ').replaceAll(RegExp(r'\[([^\]]+)\]\([^)]*\)'), r'$1');
  final end = RegExp(r'\.(\s|$)').firstMatch(para);
  return end == null ? para : para.substring(0, end.start + 1);
}

/// One heading of a page: its anchor, level, title and text.
typedef _Heading = ({String id, int level, String title, String text});

List<_Heading> _headings(String page) {
  final lines = page.split('\n');
  final found = <(int, String, int, String)>[]; // line, id, level, title
  var fence = false;
  for (var i = 0; i < lines.length; i++) {
    if (lines[i].startsWith('```')) fence = !fence;
    if (fence || i == 0) continue;
    final a = RegExp(r'^<a id="([^"]+)"></a>$').firstMatch(lines[i - 1]);
    final h = RegExp(r'^(#{1,4}) (.+)$').firstMatch(lines[i]);
    if (a != null && h != null) found.add((i, a[1]!, h[1]!.length, h[2]!));
  }
  return [
    for (var k = 0; k < found.length; k++)
      () {
        final (line, id, level, title) = found[k];
        var end = lines.length;
        for (var j = k + 1; j < found.length; j++) {
          if (found[j].$3 <= level) {
            end = found[j].$1 - 1;
            break;
          }
        }
        final text = lines.sublist(line + 1, end).where((l) => !RegExp(r'^<a id="[^"]+"></a>$').hasMatch(l)).join('\n').trim();
        return (id: id, level: level, title: title.replaceAll('`', ''), text: text);
      }(),
  ];
}

/// [page] (rendered, links resolved) cut into the sections `ui_docs` serves.
api.DocPage docPageOf(String page, PageDef def) {
  final hs = _headings(page);
  String section(String suffix) => hs.firstWhere((h) => h.id == '${def.id}-$suffix', orElse: () => (id: '', level: 0, title: '', text: '')).text;
  const skip = {'when-to-use', 'minimal-example', 'reference', 'patterns', 'pitfalls', 'see-also'};
  final itemPrefix = RegExp(r'^(node|behavior|action|type|enum|fn|trigger)-');
  final when = section('when-to-use');
  final title = hs.firstWhere((h) => h.level == 1).title;
  return api.DocPage(
    id: def.id,
    title: title,
    summary: def.id == valuesPage ? '' : _summary(page, def.id),
    when: when,
    example: section('minimal-example'),
    pitfalls: section('pitfalls'),
    sections: [
      for (final h in hs)
        if (h.level >= 2 && h.level <= 4 && h.id.startsWith('${def.id}-') && !skip.contains(h.id.substring(def.id.length + 1)) && !itemPrefix.hasMatch(h.id))
          api.DocSection(h.id, h.title, h.text.length > 3200 ? '${h.text.substring(0, h.text.lastIndexOf('\n', 3200))}\n\n(Continues: ${def.file}#${h.id}.)' : h.text),
    ],
    items: [
      ...def.nodes,
      if (def.library case final lib?) ...[for (final w in lib.widgets) w.type, for (final a in lib.actions) a.type],
      ...def.behaviors,
      ...def.triggers,
      ...def.actions,
    ],
    words: wordCount(page),
  );
}

/// The base template, rendered, cut into segments by its `<!-- if X -->`
/// ... `<!-- end -->` blocks (nested blocks add their conditions).
List<api.BaseSegment> baseSegmentsOf(String base) {
  final out = <api.BaseSegment>[];
  final stack = <List<String>>[];
  final buf = StringBuffer();
  void flush() {
    if (buf.isEmpty) return;
    out.add(api.BaseSegment([for (final c in stack) ...c], buf.toString()));
    buf.clear();
  }

  for (final l in '${base.trimRight()}\n'.split('\n')) {
    final open = RegExp(r'^<!-- if ([\w ]+) -->$').firstMatch(l);
    if (open != null) {
      flush();
      stack.add(open[1]!.split(' '));
      continue;
    }
    if (l == '<!-- end -->') {
      flush();
      if (stack.isEmpty) throw StateError('base.md: <!-- end --> without <!-- if -->');
      stack.removeLast();
      continue;
    }
    buf.writeln(l);
  }
  if (stack.isNotEmpty) throw StateError('base.md: an <!-- if --> block is not closed');
  flush();
  // The last segment's trailing newline only.
  return out;
}

String _dartString(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";

/// lib/src/core/edit/guide_topics.g.dart.
String docsSource(List<api.BaseSegment> segments, List<api.DocPage> pages, List<api.DocTask> tasks) {
  final b = StringBuffer()
    ..writeln('// Generated by tool/reference/generate.dart from tool/reference/templates and the declarations. Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'starter.dart';")
    ..writeln()
    ..writeln('/// The base (tool/reference/templates/base.md), cut by its envelope blocks: what [baseDocument] assembles.')
    ..writeln('const List<BaseSegment> baseSegments = [');
  for (final s in segments) {
    b.writeln('  BaseSegment([${s.when.map(_dartString).join(', ')}], ${_dartString(s.text)}),');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// The reference\'s pages by section: what `ui_docs` serves (`docs/reference/<id>.md`).')
    ..writeln('const List<DocPage> docPages = [');
  for (final p in pages) {
    b
      ..writeln('  DocPage(')
      ..writeln('    id: ${_dartString(p.id)},')
      ..writeln('    title: ${_dartString(p.title)},')
      ..writeln('    summary: ${_dartString(p.summary)},')
      ..writeln('    when: ${_dartString(p.when)},')
      ..writeln('    example: ${_dartString(p.example)},')
      ..writeln('    pitfalls: ${_dartString(p.pitfalls)},')
      ..writeln('    words: ${p.words},')
      ..writeln('    items: [${p.items.map(_dartString).join(', ')}],')
      ..writeln('    sections: [');
    for (final s in p.sections) {
      b.writeln('      DocSection(${_dartString(s.id)}, ${_dartString(s.title)}, ${_dartString(s.text)}),');
    }
    b
      ..writeln('    ],')
      ..writeln('  ),');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// The index\'s task table: a need and the section that answers it.')
    ..writeln('const List<DocTask> docTasks = [');
  for (final t in tasks) {
    b.writeln('  (need: ${_dartString(t.need)}, anchor: ${_dartString(t.anchor)}),');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// Topic names kept from earlier `ui_docs` versions, and the section each answers with.')
    ..writeln('const Map<String, String> docAliases = {');
  for (final e in topicAliases.entries) {
    b.writeln('  ${_dartString(e.key)}: ${_dartString(e.value)},');
  }
  b.writeln('};');
  return b.toString();
}

Map<String, Object?> _indexJson(Renderer r, List<api.DocPage> pages, List<api.DocTask> tasks, Map<String, String> out) {
  int words(String f) => wordCount(out['docs/reference/$f'] ?? '');
  return {
    'version': r.catalog['version'],
    'base': {
      'files': {'file': 'STARTER.md', 'words': words('STARTER.md')},
      'runtime': {'file': 'RUNTIME_STARTER.md', 'words': words('RUNTIME_STARTER.md')},
    },
    'topics': [
      for (final p in pages) ...[
        {'topic': p.id, 'file': p.file, 'anchor': 'page-${p.id}', 'title': p.title, 'summary': p.summary, 'words': p.words},
        for (final s in p.sections)
          {'topic': s.id, 'file': p.file, 'anchor': s.id, 'title': s.title, 'summary': _firstSentence(s.text), 'words': wordCount(s.text)},
      ],
    ],
    'tasks': [for (final t in tasks) {'need': t.need, 'file': r.anchors[t.anchor], 'anchor': t.anchor}],
    'items': {
      for (final kind in ItemKind.values)
        kind.name: {for (final e in r.assignment[kind]!.entries) e.key: '${e.value}.md#${kind.anchor(e.key)}'},
    },
  };
}

String _firstSentence(String text) {
  final para = text.split('\n\n').firstWhere((p) => !p.startsWith('|') && !p.startsWith('```'), orElse: () => '');
  final flat = para.replaceAll('\n', ' ').replaceAll(RegExp(r'\[([^\]]+)\]\([^)]*\)'), r'$1');
  final end = RegExp(r'\.(\s|$)').firstMatch(flat);
  return end == null ? flat : flat.substring(0, end.start + 1);
}

/// An old page, now a list of where each of its items went (so old links
/// keep working).
String _stub(Renderer r, String file, String title) {
  final rows = <String>[];
  void items(ItemKind kind) {
    final entries = r.assignment[kind]!.entries.toList();
    for (final e in entries) {
      rows.add('- <a id="${kind.anchor(e.key)}"></a>`${e.key}`: [${e.value}.md#${kind.anchor(e.key)}](${e.value}.md#${kind.anchor(e.key)})');
    }
  }

  switch (file) {
    case 'nodes.md':
      items(ItemKind.node);
    case 'behaviors.md':
      items(ItemKind.behavior);
    case 'triggers.md':
      items(ItemKind.trigger);
    case 'actions.md':
      items(ItemKind.action);
    case 'formulas.md':
      rows.add('- Every function, grouped: [state.md#state-formula-functions](state.md#state-formula-functions)');
    case 'bindings.md':
      rows
        ..add('- Binding paths and the value each expects: [state.md#state-binding-paths](state.md#state-binding-paths)')
        ..add('- Expressions: [state.md#state-expressions](state.md#state-expressions)');
    case 'variables-conditions-scripts.md':
      rows
        ..add('- Variables: [state.md#state-variables](state.md#state-variables)')
        ..add('- Conditions: [state.md#state-conditions](state.md#state-conditions)')
        ..add('- Scripts: [state.md#state-scripts](state.md#state-scripts)')
        ..add('- Breakpoints: [layout.md#layout-breakpoints](layout.md#layout-breakpoints)');
  }
  final text = r.template('stub.md', fills: {'title': () => title, 'entries': () => rows.join('\n')});
  return '${r.generatedNote()}\n<a id="page-${file.replaceAll('.md', '')}"></a>\n$text\n';
}

String _missing(Catalog c) {
  final byArea = <String, List<String>>{};
  for (final m in c.missing) {
    (byArea[m.area] ??= []).add(m.name);
  }
  final b = StringBuffer()
    ..writeln('<!-- Generated by tool/reference/generate.dart. Do not edit. -->')
    ..writeln('# Declarations without documentation')
    ..writeln()
    ..writeln('${c.missing.length} declarations have neither a `doc:` string nor a `///` comment (nor a documented model field of the same name). '
        'The reference shows them without a description rather than inventing one. Many are Flutter parameters whose '
        'meaning is Flutter\'s (`mainAxisAlignment`); the list is here so they can be documented at the declaration.')
    ..writeln();
  for (final e in byArea.entries) {
    b
      ..writeln('## ${e.key} (${e.value.length})')
      ..writeln()
      ..writeln(e.value.join(', '))
      ..writeln();
  }
  return b.toString();
}
