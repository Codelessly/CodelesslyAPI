// Builds every file of docs/reference from the declarations.
import 'dart:convert';

import 'package:codelessly_api/codelessly_api.dart' as api;

import 'catalog.dart';
import 'markdown.dart';
import 'schema.dart';

/// The reference files, by path relative to the package root.
Map<String, String> buildReference(String root) {
  final catalog = Catalog(root);
  final json = catalog.json;
  final pages = Pages(json, root).render();
  final single = Pages(json, root, mode: LinkMode.single).render();
  final compact = Pages(json, root, mode: LinkMode.single, compact: true).render();
  String joined(Map<String, String> p) => [for (final name in Pages.order) p[name]!.trimRight()].join('\n\n---\n\n');
  final out = <String, String>{
    for (final e in pages.entries) 'docs/reference/${e.key}': e.value,
    'docs/reference/API_REFERENCE.md': '${joined(single)}\n',
    'docs/reference/API_REFERENCE.compact.md': '${joined(compact)}\n',
    'docs/reference/catalog.json': '${const JsonEncoder.withIndent('  ').convert(json)}\n',
    'docs/reference/document.schema.json': '${const JsonEncoder.withIndent('  ').convert(SchemaBuilder().build())}\n',
    'docs/reference/_missing_docs.md': _missing(catalog),
    // The two tools a model is given, for the agent profile over the core.
    'docs/reference/ui_tools.json':
        '${const JsonEncoder.withIndent('  ').convert(api.uiTools(api.TrustProfile.agent.restrict(api.Catalog.core)))}\n',
  };
  return out;
}

String _missing(Catalog c) {
  final byArea = <String, List<String>>{};
  for (final m in c.missing) {
    (byArea[m.area] ??= []).add(m.name);
  }
  final b = StringBuffer()
    ..writeln('<!-- Generated by tool/reference/generate.dart. Do not edit. -->')
    ..writeln('# Declarations without documentation')
    ..writeln()
    ..writeln('${c.missing.length} declarations have neither a `doc:` string nor a `///` comment (nor a documented model field of the same name). '
        'The reference shows them without a description rather than inventing one. Many are Flutter parameters whose '
        'meaning is Flutter\'s (`mainAxisAlignment`); the list is here so they can be documented at the declaration.')
    ..writeln();
  for (final e in byArea.entries) {
    b
      ..writeln('## ${e.key} (${e.value.length})')
      ..writeln()
      ..writeln(e.value.join(', '))
      ..writeln();
  }
  return b.toString();
}
