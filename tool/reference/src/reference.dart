// Builds every file of docs/reference from the declarations.
import 'dart:convert';

import 'package:codelessly_api/codelessly_api.dart' as api;

import 'catalog.dart';
import 'markdown.dart';
import 'schema.dart';

/// The reference files, by path relative to the package root.
Map<String, String> buildReference(String root) {
  final catalog = Catalog(root);
  final json = catalog.json;
  final pages = Pages(json, root).render();
  final single = Pages(json, root, mode: LinkMode.single).render();
  final compact = Pages(json, root, mode: LinkMode.single, compact: true).render();
  String joined(Map<String, String> p) => [for (final name in Pages.order) p[name]!.trimRight()].join('\n\n---\n\n');
  final out = <String, String>{
    for (final e in pages.entries) 'docs/reference/${e.key}': e.value,
    'docs/reference/API_REFERENCE.md': '${joined(single)}\n',
    'docs/reference/API_REFERENCE.compact.md': '${joined(compact)}\n',
    'docs/reference/catalog.json': '${const JsonEncoder.withIndent('  ').convert(json)}\n',
    'docs/reference/document.schema.json': '${const JsonEncoder.withIndent('  ').convert(SchemaBuilder().build())}\n',
    'docs/reference/_missing_docs.md': _missing(catalog),
    // The two tools a model is given, for the agent profile over the core.
    'docs/reference/ui_tools.json':
        '${const JsonEncoder.withIndent('  ').convert(api.uiTools(api.TrustProfile.agent.restrict(api.Catalog.core)))}\n',
    // The compact tools and the runtime starter they go with.
    'docs/reference/ui_tools.compact.json':
        '${const JsonEncoder.withIndent('  ').convert(api.uiTools(api.TrustProfile.agent.restrict(api.Catalog.core), compact: true))}\n',
    'docs/reference/RUNTIME_STARTER.md': '<!-- Generated by tool/reference/generate.dart (runtimeStarter()). Do not edit. -->\n'
        '${api.runtimeStarter()}',
    // The feature areas ui_docs serves, from the same guide sections.
    'lib/src/core/edit/guide_topics.g.dart': guideTopicsSource(pages['index.md']!),
  };
  return out;
}

String _missing(Catalog c) {
  final byArea = <String, List<String>>{};
  for (final m in c.missing) {
    (byArea[m.area] ??= []).add(m.name);
  }
  final b = StringBuffer()
    ..writeln('<!-- Generated by tool/reference/generate.dart. Do not edit. -->')
    ..writeln('# Declarations without documentation')
    ..writeln()
    ..writeln('${c.missing.length} declarations have neither a `doc:` string nor a `///` comment (nor a documented model field of the same name). '
        'The reference shows them without a description rather than inventing one. Many are Flutter parameters whose '
        'meaning is Flutter\'s (`mainAxisAlignment`); the list is here so they can be documented at the declaration.')
    ..writeln();
  for (final e in byArea.entries) {
    b
      ..writeln('## ${e.key} (${e.value.length})')
      ..writeln()
      ..writeln(e.value.join(', '))
      ..writeln();
  }
  return b.toString();
}

/// The guide's sections `ui_docs` serves by area name, and their anchors.
const Map<String, String> guideTopicAnchors = {
  'theme': 'guide-theme', 'layout': 'guide-layout', 'decoration': 'guide-decoration', 'text': 'guide-text', //
  'screens': 'guide-screens', 'responsive': 'guide-responsive', 'variables': 'guide-variables',
  'conditions': 'guide-conditions', 'reactions': 'guide-reactions', 'states': 'guide-states', 'scrolling': 'guide-scrolling',
  'lists': 'guide-lists', 'forms': 'guide-forms', 'modals': 'guide-modals', 'images': 'guide-images',
  'components': 'guide-components', 'pitfalls': 'guide-pitfalls',
};

/// lib/src/core/edit/guide_topics.g.dart: each section of the rendered guide
/// [index] named in [guideTopicAnchors], trimmed to about 2,600 characters
/// (prose first, at most one example that fits), links reduced to their
/// text.
String guideTopicsSource(String index) {
  final b = StringBuffer()
    ..writeln('// Generated by tool/reference/generate.dart from the guide (docs/reference/index.md). Do not edit.')
    ..writeln()
    ..writeln('/// The guide\'s feature areas, each a section of docs/reference/index.md')
    ..writeln('/// trimmed to a tool result: what `ui_docs` answers for an area.')
    ..writeln('const Map<String, ({String title, String text})> guideTopics = {');
  for (final e in guideTopicAnchors.entries) {
    final start = index.indexOf('<a id="${e.value}"></a>');
    if (start < 0) throw StateError('guide topic ${e.key}: no section ${e.value}');
    final next = index.indexOf('<a id="guide-', start + 10);
    var section = index.substring(start, next < 0 ? index.length : next);
    section = section.replaceAll(RegExp(r'<a id="[^"]*"></a>\n?'), '');
    final lines = section.trim().split('\n');
    final title = lines.first.replaceFirst(RegExp(r'^#+\s*(\d+\.\s*)?'), '').trim();
    final body = lines.skip(1).join('\n').replaceAllMapped(RegExp(r'\[([^\]]+)\]\([^)]*\)'), (m) => m[1]!);
    // Blocks: paragraphs and fenced code.
    final blocks = <String>[];
    final buf = StringBuffer();
    var fence = false;
    for (final l in body.split('\n')) {
      if (l.startsWith('```')) fence = !fence;
      if (!fence && l.trim().isEmpty && !l.startsWith('```')) {
        if (buf.isNotEmpty) blocks.add(buf.toString().trimRight());
        buf.clear();
      } else {
        buf.writeln(l);
      }
    }
    if (buf.isNotEmpty) blocks.add(buf.toString().trimRight());
    final kept = <String>[];
    var size = 0;
    var code = false;
    for (final blk in blocks) {
      final isCode = blk.startsWith('```');
      if (isCode && (code || blk.length > 1400)) continue;
      if (size + blk.length > 2600) continue;
      kept.add(blk);
      size += blk.length;
      if (isCode) code = true;
    }
    kept.add('(The whole section: docs/reference/index.md#${e.value}.)');
    final text = kept.join('\n\n');
    b.writeln("  '${e.key}': (title: ${_dartString(title)}, text: ${_dartString(text)}),");
  }
  b.writeln('};');
  return b.toString();
}

String _dartString(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";
